const SHELL_CACHE = `gba-shell-${VERSION}`;
const ROM_CACHE = "gba-roms";
const RUNTIME_CACHE = "gba-runtime";
const FONT_CACHE = "gba-fonts";
const NAVIGATION_TIMEOUT = 3000;

const scopeUrl = new URL(self.registration ? self.registration.scope : "./", self.location);
const toUrl = (path) => new URL(path, scopeUrl).href;
const PRECACHE_URLS = new Set(PRECACHE.map(([path]) => toUrl(path)));

self.addEventListener("install", (event) => {
    event.waitUntil((async () => {
        const cache = await caches.open(SHELL_CACHE);
        // cache: "reload" skips the HTTP cache so a deploy never precaches stale files.
        await Promise.all(PRECACHE.map(async ([path, revision]) => {
            const response = await fetch(new Request(toUrl(path), { cache: "reload" }));
            if (!response.ok) {
                throw new Error(`Precache failed for ${path} (${response.status}) at revision ${revision}`);
            }
            // Re-wrap redirected responses: browsers refuse them for navigations.
            const body = response.redirected ? new Response(await response.blob(), { headers: response.headers }) : response;
            await cache.put(toUrl(path), body);
        }));
    })());
});

self.addEventListener("activate", (event) => {
    event.waitUntil((async () => {
        const names = await caches.keys();
        await Promise.all(names.filter((name) => name.startsWith("gba-shell-") && name !== SHELL_CACHE).map((name) => caches.delete(name)));
        await self.clients.claim();
    })());
});

self.addEventListener("message", (event) => {
    if (event.data && event.data.type === "SKIP_WAITING") {
        self.skipWaiting();
    }
    else if (event.data && event.data.type === "GET_VERSION" && event.ports[0]) {
        event.ports[0].postMessage({ version: VERSION });
    }
});

self.addEventListener("fetch", (event) => {
    const request = event.request;
    if (request.method !== "GET") {
        return;
    }
    const url = new URL(request.url);

    if (url.origin === "https://fonts.googleapis.com") {
        event.respondWith(staleWhileRevalidate(request, FONT_CACHE));
        return;
    }
    if (url.origin === "https://fonts.gstatic.com") {
        event.respondWith(cacheFirst(request, FONT_CACHE));
        return;
    }
    if (url.origin !== self.location.origin) {
        return;
    }
    if (request.mode === "navigate") {
        event.respondWith(networkFirstPage(request));
        return;
    }
    if (/\.gba$/i.test(url.pathname)) {
        event.respondWith(cacheFirst(request, ROM_CACHE, { ignoreSearch: true }));
        return;
    }
    const clean = url.origin + url.pathname;
    if (PRECACHE_URLS.has(clean)) {
        event.respondWith(caches.match(clean, { cacheName: SHELL_CACHE }).then((cached) => cached || fetch(request)));
        return;
    }
    event.respondWith(staleWhileRevalidate(request, RUNTIME_CACHE));
});

async function networkFirstPage(request) {
    const url = new URL(request.url);
    const key = url.origin + url.pathname;
    try {
        const response = await Promise.race([
            fetch(request),
            new Promise((resolve, reject) => setTimeout(() => reject(new Error("timeout")), NAVIGATION_TIMEOUT))
        ]);
        if (response.ok && PRECACHE_URLS.has(key)) {
            const cache = await caches.open(SHELL_CACHE);
            cache.put(key, response.clone());
        }
        return response;
    }
    catch (error) {
        const cached = await caches.match(key, { ignoreSearch: true })
            || await caches.match(toUrl(url.pathname.endsWith("/") ? "index.html" : url.pathname.split("/").pop()))
            || await caches.match(toUrl("index.html"));
        return cached || new Response("You're offline and this page hasn't been saved yet.", { status: 503, headers: { "Content-Type": "text/plain; charset=utf-8" } });
    }
}

async function cacheFirst(request, cacheName, options = {}) {
    const cache = await caches.open(cacheName);
    const cached = await cache.match(request, options);
    if (cached) {
        return cached;
    }
    const response = await fetch(request);
    // Opaque (status 0) responses are allowed for fonts only.
    if (response.ok || (response.type === "opaque" && cacheName === FONT_CACHE)) {
        cache.put(request, response.clone()).catch(() => {});
    }
    return response;
}

async function staleWhileRevalidate(request, cacheName) {
    const cache = await caches.open(cacheName);
    const cached = await cache.match(request);
    const network = fetch(request).then((response) => {
        if (response.ok || response.type === "opaque") {
            cache.put(request, response.clone()).catch(() => {});
        }
        return response;
    }).catch(() => cached);
    return cached || network;
}
