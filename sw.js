/*
 Service worker for GBA (hand-written; the project has no bundler, so no Workbox).

 Caches
   gba-shell-<VERSION>  precached app shell: HTML, CSS, JS, emulator core, BIOS, icons.
                        Rebuilt on every deploy (VERSION changes); old ones are deleted.
   gba-roms             ROMs, cached the first time a game is played (cache-first), so played
                        games work offline. Kept across updates. ROMs are never precached
                        (the library is several GB).
   gba-runtime          other same-origin files such as cover art (stale-while-revalidate).
   gba-fonts            Google Fonts (CSS stale-while-revalidate, font files cache-first).

 Strategies
   navigations          network-first (3 s timeout), falling back to the cached page.
   precached files      cache-first (they are versioned by the precache manifest).

 Updates: a new sw.js installs in the background and waits; the page shows "Update available"
 and posts SKIP_WAITING when the user chooses Reload.

 The block between the precache markers is generated by `npm run build:sw`
 (scripts/build-sw.mjs). Don't edit it by hand.
 */

